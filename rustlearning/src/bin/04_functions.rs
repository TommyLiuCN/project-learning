// ============================================================
// 第4章 · 函数：参数、返回值与「表达式语言」
// ============================================================
// 运行: cargo run --bin 04_functions
// 学习要点:
//   1. fn 定义函数，参数必须标注类型
//   2. 语句 vs 表达式：返回值就是最后一个表达式（不加分号）
//   3. 提前返回 return
//   4. 文档注释 /// 与 rustdoc
//   5. 递归（对比 C/Python）
//   6. 单元类型 () —— Rust 的 void
// ============================================================

/// 两数之和。
/// /// 是文档注释，cargo doc 会生成网页文档；
/// 对比 Python 的 docstring、C 的 Doxygen 注释——Rust 原生内置。
fn add(a: i32, b: i32) -> i32 {
    a + b                    // 没有分号！这是表达式，值就是返回值
    // 写成 a + b; 反而编译错误：加了分号变成语句，返回 () 而函数要 i32
}

/// 显式 return 的版本（提前退出时才需要）
fn abs(x: i32) -> i32 {
    if x < 0 {
        return -x;           // return 用于中途返回，像 C/Python
    }
    x                        // 正常路径走「最后表达式」风格
}

/// 返回多个值：用元组（像 Python 返回 tuple）
fn divmod(a: i32, b: i32) -> (i32, i32) {
    (a / b, a % b)
}

/// 返回 ()：没有值得写的函数。-> () 可省略。
/// 对比 C 的 void；Python 隐式返回 None。() 就是 Rust 的 None/void 三兄弟。
fn greet(name: &str) {
    println!("你好, {name}!");
}

/// 无限递归会编译警告；有终止条件的递归和 C/Python 写法一致
fn factorial(n: u64) -> u64 {
    if n <= 1 { 1 } else { n * factorial(n - 1) }    // if 表达式直接当返回值
}

fn main() {
    // ==== 1. 基本调用 ====
    println!("add(2,3) = {}", add(2, 3));
    println!("abs(-7) = {}", abs(-7));
    greet("世界");
    let (q, r) = divmod(17, 5);              // 元组解构接收多返回值
    println!("17 ÷ 5 = 商{q} 余{r}");
    println!("10! = {}", factorial(10));

    // ==== 2. 语句 vs 表达式：理解 Rust 的关键 ====
    // 语句执行动作不产生值（let x = ...;）；表达式求值产生值。
    let y = {
        let x = 3;
        x + 1                                // 块的最后一个表达式 = 块的值 = y
        // 若写成 x + 1; 则块返回 ()，y 就成了空元组——新手最常见报错之一
    };
    println!("块表达式 y = {y}");

    // ==== 3. 函数类型作为参数？先看闭包预告 ====
    // C 用函数指针 void (*fp)(int)；Python 直接传函数名。Rust 平时用闭包+trait 约束：
    fn apply(f: impl Fn(i32) -> i32, v: i32) -> i32 {
        f(v)                                 // impl Fn(...) 的完整语法第9/11章展开
    }
    println!("apply(|x| x*10, 5) = {}", apply(|x| x * 10, 5));

    // ==== 4. 永不返回的函数 ====
    // ! 类型：发散函数。panic!/process::exit 都是这个套路。
    fn bomb() -> ! {
        panic!("爆炸了");                     // 永远不会正常返回
    }
    let _desc = "普通字符串";
    println!("bomb 只定义未调用（调用就崩）");
    let _ = bomb;                            // 仅引用不调用，避免真的 panic

    /*
     * ---- 一句话总结 ----
     * 参数类型必标、返回类型 -> 标注；
     * 「最后的不带分号的表达式是返回值」是 Rust 和 C/Python 最大的手感差异；
     * 多返回值用元组解构；文档注释 /// 一等公民。
     */
}
